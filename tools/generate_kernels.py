"""Generate ``src/inazumaq2n/_direct.h``, the kernels for one to four bands.

The kernels compute the centered moments of one tile of a pair of images
with one to four bands, without a pixel workspace. They are written in
terms of an eight-lane vector whose operations ``_isa.h`` defines for each
instruction set, and ``_isa.h`` includes the generated file once for every
sample type, so one text serves every instruction set and input type.

Run without arguments to rewrite the file, or with ``--check`` to verify
that the file in the repository is what this script generates.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / "src" / "inazumaq2n" / "_direct.h"

BANDS = (1, 2, 3, 4)

HEADER = """\
/*
 * Generated by tools/generate_kernels.py. Do not edit.
 *
 * Centered moments of one tile for images of one to four bands. This file
 * is included by _isa.h once for every sample type Q2N_T, with V8_LOAD
 * reading eight consecutive samples of that type as doubles, and with the
 * eight-lane vector V8 of the instruction set that _isa.h is defining.
 *
 * A tile is traversed twice. The first pass sums the differences from an
 * anchor, the first sample of the tile, and gives the means. The second
 * pass accumulates the centered squares and the centered cross products
 * with fused multiply-adds. Within a row, column v belongs to lane v mod 8
 * for the columns below the largest multiple of eight, and to one scalar
 * accumulator for the rest; the lanes are added in the fixed order of
 * V8_REDUCE. Every instruction set therefore performs the same operations
 * in the same order, and the results are bit-identical between them.
 *
 * The tile functions write the B * B cross moments to g and the statistics
 * to s in the order mean x, mean y, sum of squares x, sum of squares y.
 * The functions with suffix r read rows and columns beyond the image
 * through the symmetric reflection; the others require a tile that lies
 * inside the image.
 */
"""

DRIVER_HEAD = """\
// Centered moments of count tiles of an image pair with one to four bands
static void KNAME(direct)(const void* xv, const void* yv, ptrdiff_t h, ptrdiff_t w,
        ptrdiff_t bands, const int32_t* origins, ptrdiff_t count, ptrdiff_t side,
        double* grams, double* stats) {
    const Q2N_T* x = (const Q2N_T*)xv;
    const Q2N_T* y = (const Q2N_T*)yv;

    for (ptrdiff_t t = 0; t < count; t++) {
        const ptrdiff_t r = origins[2 * t], c = origins[2 * t + 1];
        const int inside = r + side <= h && c + side <= w;
        double* g = grams + t * bands * bands;
        double* s = stats + t * 4 * bands;

        switch (bands) {
"""

DRIVER_TAIL = """\
        default:
            break;
        }
    }
}
"""


def loaders(bands: int) -> str:
    """Return the functions that load eight pixels of ``bands`` bands."""
    b = bands
    if b == 1:
        return """\
// Load eight samples of one band from column c of a row, reflecting at the edge
Q2N_INLINE Q2N_TARGET V8 KNAME(span1)(const Q2N_T* row, ptrdiff_t w, ptrdiff_t c) {
    double t[8];

    if (c + 8 <= w) return V8_LOAD(row + c);
    if (c >= w) return V8_REVERSE(V8_LOAD(row + (2 * w - 8 - c)));
    for (ptrdiff_t j = 0; j < 8; j++) {
        t[j] = (double)row[c + j < w ? c + j : 2 * w - 1 - c - j];
    }
    return V8_LOAD_F64(t);
}
"""
    outs = ", ".join(f"V8* a{i}" for i in range(b))
    names = ", ".join(f"a{i}" for i in range(b))
    loads = ", ".join(
        "V8_LOAD(p)" if k == 0 else f"V8_LOAD(p + {8 * k})" for k in range(b)
    )
    lines = [
        f"// Load eight pixels of {b} interleaved bands into one vector per band",
        f"Q2N_INLINE Q2N_TARGET void KNAME(load{b})(const Q2N_T* p, {outs}) {{",
        f"    V8_DEINTERLEAVE{b}({loads},",
        f"            {names});",
        "}",
        "",
        f"// Load eight {b}-band pixels from column c of a row, reflecting at the edge",
        f"Q2N_INLINE Q2N_TARGET void KNAME(span{b})(const Q2N_T* row, ptrdiff_t w,"
        " ptrdiff_t c,",
        f"        {outs}) {{",
        "    double " + ", ".join(f"t{i}[8]" for i in range(b)) + ";",
        "",
        "    if (c + 8 <= w) {",
        f"        KNAME(load{b})(row + {b} * c, {names});",
        "        return;",
        "    }",
        "    if (c >= w) {",
        f"        KNAME(load{b})(row + {b} * (2 * w - 8 - c), {names});",
    ]
    lines += [f"        *a{i} = V8_REVERSE(*a{i});" for i in range(b)]
    lines += [
        "        return;",
        "    }",
        "    for (ptrdiff_t j = 0; j < 8; j++) {",
        "        const ptrdiff_t cc = c + j < w ? c + j : 2 * w - 1 - c - j;",
        f"        const Q2N_T* at = row + {b} * cc;",
        "",
    ]
    lines += [f"        t{i}[j] = (double)at[{i}];" for i in range(b)]
    lines += ["    }"]
    lines += [f"    *a{i} = V8_LOAD_F64(t{i});" for i in range(b)]
    lines += ["}"]
    return "\n".join(lines) + "\n"


def driver() -> str:
    """Return the function that dispatches every tile to its kernel."""
    lines = [DRIVER_HEAD.rstrip("\n")]
    for b in BANDS:
        lines += [
            f"        case {b}:",
            "            if (inside) {",
            f"                KNAME(tile{b})(x, y, w, r, c, side, g, s);",
            "            } else {",
            f"                KNAME(tile{b}r)(x, y, h, w, r, c, side, g, s);",
            "            }",
            "            break;",
        ]
    lines.append(DRIVER_TAIL.rstrip("\n"))
    return "\n".join(lines) + "\n"


def joined(items: list[str], indent: str, prefix: str = "") -> list[str]:
    """Return declarations of ``items`` wrapped to the line length."""
    lines: list[str] = []
    current = indent + prefix
    for index, item in enumerate(items):
        piece = item + ("," if index + 1 < len(items) else ";")
        if len(current) + len(piece) + 1 > 88 and current.strip() != prefix.strip():
            lines.append(current.rstrip())
            current = indent + "        "
        current += piece + " "
    lines.append(current.rstrip())
    return lines


def sweep(bands: int, reflected: bool, vector: list[str], tail: list[str]) -> list[str]:
    """Return one pass over the tile with the given loop bodies."""
    b = bands
    lines = ["    for (ptrdiff_t u = 0; u < side; u++) {"]
    if reflected:
        lines += [
            "        const ptrdiff_t rr = r + u < h ? r + u : 2 * h - 1 - r - u;",
            f"        const Q2N_T* px = x + rr * w * {b};",
            f"        const Q2N_T* py = y + rr * w * {b};",
        ]
    else:
        lines += [
            f"        const Q2N_T* px = bx + u * w * {b};",
            f"        const Q2N_T* py = by + u * w * {b};",
        ]
    lines += ["        ptrdiff_t v = 0;", "", "        for (; v < full; v += 8) {"]
    if b == 1:
        if reflected:
            lines += [
                "            V8 a0 = KNAME(span1)(px, w, c + v);",
                "            V8 d0 = KNAME(span1)(py, w, c + v);",
                "",
            ]
        else:
            lines += [
                "            V8 a0 = V8_LOAD(px + v);",
                "            V8 d0 = V8_LOAD(py + v);",
                "",
            ]
    else:
        xs = ", ".join(f"&a{i}" for i in range(b))
        ys = ", ".join(f"&d{i}" for i in range(b))
        names = ", ".join([f"a{i}" for i in range(b)] + [f"d{i}" for i in range(b)])
        lines += [f"            V8 {names};", ""]
        if reflected:
            lines += [
                f"            KNAME(span{b})(px, w, c + v, {xs});",
                f"            KNAME(span{b})(py, w, c + v, {ys});",
            ]
        else:
            lines += [
                f"            KNAME(load{b})(px + {b} * v, {xs});",
                f"            KNAME(load{b})(py + {b} * v, {ys});",
            ]
    lines += ["            " + line for line in vector]
    lines += ["        }", "        for (; v < side; v++) {"]
    if reflected:
        lines += [
            "            const ptrdiff_t cc = c + v < w ? c + v : 2 * w - 1 - c - v;",
            f"            const Q2N_T* qx = px + {b} * cc;",
            f"            const Q2N_T* qy = py + {b} * cc;",
        ]
    else:
        lines += [
            f"            const Q2N_T* qx = px + {b} * v;",
            f"            const Q2N_T* qy = py + {b} * v;",
        ]
    lines += ["            " + line for line in tail]
    lines += ["        }", "    }"]
    return lines


def tile(bands: int, reflected: bool) -> str:
    """Return the tile function for ``bands`` bands."""
    b = bands
    idx = range(b)
    pairs = [(i, j) for i in idx for j in idx]
    name = f"tile{b}" + ("r" if reflected else "")
    where = "reflected at the image edge" if reflected else "inside the image"
    lines = [
        f"// Centered moments of one tile with {b} band{'s' if b > 1 else ''}, {where}",
        f"static Q2N_TARGET void KNAME({name})(const Q2N_T* x, const Q2N_T* y,"
        + (" ptrdiff_t h," if reflected else ""),
        "        ptrdiff_t w, ptrdiff_t r, ptrdiff_t c, ptrdiff_t side, double* g,"
        " double* s) {",
        "    const double p = (double)side * (double)side;",
        "    const ptrdiff_t full = side - side % 8;",
    ]
    if reflected:
        lines += [
            "    const ptrdiff_t ar = r < h ? r : 2 * h - 1 - r;",
            "    const ptrdiff_t ac = c < w ? c : 2 * w - 1 - c;",
            f"    const Q2N_T* bx = x + (ar * w + ac) * {b};",
            f"    const Q2N_T* by = y + (ar * w + ac) * {b};",
        ]
    else:
        lines += [
            f"    const Q2N_T* bx = x + (r * w + c) * {b};",
            f"    const Q2N_T* by = y + (r * w + c) * {b};",
        ]
    for i in idx:
        lines.append(
            f"    const double ax{i} = (double)bx[{i}], ay{i} = (double)by[{i}];"
        )
    for i in idx:
        lines.append(f"    const V8 vax{i} = V8_SET1(ax{i}), vay{i} = V8_SET1(ay{i});")
    sums = [f"s{k}{i}" for k in "xy" for i in idx]
    lines += joined([f"{n} = V8_ZERO()" for n in sums], "    ", "V8 ")
    lines += joined([f"t{n} = 0.0" for n in sums], "    ", "double ")
    lines += joined([f"m{k}{i}" for k in "xy" for i in idx], "    ", "double ")
    moments = [f"{k}{i}" for k in ("xx", "yy") for i in idx]
    moments += [f"g{i}{j}" for i, j in pairs]
    lines += joined([f"{n} = V8_ZERO()" for n in moments], "    ", "V8 ")
    lines += joined([f"t{n} = 0.0" for n in moments], "    ", "double ")
    lines += joined([f"vm{k}{i}" for k in "xy" for i in idx], "    ", "V8 ")
    lines.append("")

    vector, tail = [], []
    for i in idx:
        vector += [
            f"sx{i} = V8_ADD(sx{i}, V8_SUB(a{i}, vax{i}));",
            f"sy{i} = V8_ADD(sy{i}, V8_SUB(d{i}, vay{i}));",
        ]
        tail += [
            f"tsx{i} += (double)qx[{i}] - ax{i};",
            f"tsy{i} += (double)qy[{i}] - ay{i};",
        ]
    lines += sweep(b, reflected, vector, tail)
    for i in idx:
        lines += [
            f"    mx{i} = ax{i} + (V8_REDUCE(sx{i}) + tsx{i}) / p;",
            f"    my{i} = ay{i} + (V8_REDUCE(sy{i}) + tsy{i}) / p;",
        ]
    for i in idx:
        lines += [
            f"    vmx{i} = V8_SET1(mx{i});",
            f"    vmy{i} = V8_SET1(my{i});",
        ]

    vector, tail = [], []
    for i in idx:
        vector += [
            f"a{i} = V8_SUB(a{i}, vmx{i});",
            f"d{i} = V8_SUB(d{i}, vmy{i});",
            f"xx{i} = V8_FMADD(a{i}, a{i}, xx{i});",
            f"yy{i} = V8_FMADD(d{i}, d{i}, yy{i});",
        ]
        tail += [
            f"const double a{i} = (double)qx[{i}] - mx{i};",
            f"const double d{i} = (double)qy[{i}] - my{i};",
        ]
    tail.append("")
    for i in idx:
        tail += [
            f"txx{i} = fma(a{i}, a{i}, txx{i});",
            f"tyy{i} = fma(d{i}, d{i}, tyy{i});",
        ]
    for i, j in pairs:
        vector.append(f"g{i}{j} = V8_FMADD(a{i}, d{j}, g{i}{j});")
        tail.append(f"tg{i}{j} = fma(a{i}, d{j}, tg{i}{j});")
    lines += sweep(b, reflected, vector, tail)

    for i in idx:
        lines += [f"    s[{i}] = mx{i};", f"    s[{b + i}] = my{i};"]
    for i in idx:
        lines += [
            f"    s[{2 * b + i}] = V8_REDUCE(xx{i}) + txx{i};",
            f"    s[{3 * b + i}] = V8_REDUCE(yy{i}) + tyy{i};",
        ]
    for i, j in pairs:
        lines.append(f"    g[{i * b + j}] = V8_REDUCE(g{i}{j}) + tg{i}{j};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate() -> str:
    """Return the text of the generated header."""
    parts = [HEADER]
    for bands in BANDS:
        parts.append(loaders(bands))
        for reflected in (False, True):
            parts.append(tile(bands, reflected))
    parts.append(driver())
    return "\n".join(parts)


def main() -> int:
    """Write the header, or compare it with the file in the repository."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit with status 1 if the file differs from the generated text",
    )
    arguments = parser.parse_args()
    text = generate()
    if arguments.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} is out of date; run tools/generate_kernels.py")
            return 1
        print(f"{OUTPUT.name} is up to date")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
